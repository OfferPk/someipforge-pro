/**
 * SOMEIPForge Pro - Automotive Gateway Firewall & AUTOSAR Config Synthesizer
 * Generates Linux nftables rules, Suricata SOME/IP L7 signatures, and AUTOSAR ARXML models.
 */

(function (root, factory) {
  if (typeof define === 'function' && define.amd) {
    define([], factory);
  } else if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.SOMEIPConfigSynthesizer = factory();
  }
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  /**
   * Generates Linux nftables automotive gateway filtering rules for SOME/IP & SOME/IP-SD
   */
  function generateNftablesRules(config) {
    config = config || {};
    var sdPort = config.sdPort || 30490;
    var servicePort = config.servicePort || 30501;
    var iviIface = config.iviInterface || 'eth0.200';
    var adasIface = config.adasInterface || 'eth1.300';
    var maxSdRate = config.maxSdRate || '10/second';
    var authorizedAdasIps = config.authorizedAdasIps || ['192.168.1.10', '192.168.1.20', '192.168.1.30'];

    var ipList = authorizedAdasIps.join(', ');

    return [
      '#!/usr/sbin/nft -f',
      '# SOMEIPForge Pro - Automotive Gateway Ingress & Domain Isolation Rules',
      '# Standard: AUTOSAR Adaptive SOA / ISO 21434 Zero-Trust Gateway',
      '',
      'flush ruleset',
      '',
      'table ip automotive_soa {',
      '    # Authorized Autonomous Driving (ADAS) ECUs',
      '    set adas_nodes {',
      '        type ipv4_addr',
      '        elements = { ' + ipList + ' }',
      '    }',
      '',
      '    chain input {',
      '        type filter hook input priority filter; policy drop;',
      '',
      '        # Allow loopback and established connections',
      '        iif "lo" accept',
      '        ct state established,related accept',
      '        ct state invalid drop',
      '',
      '        # 1. Rate-limit SOME/IP-SD Multicast (224.0.0.17 UDP ' + sdPort + ')',
      '        ip daddr 224.0.0.17 udp dport ' + sdPort + ' limit rate ' + maxSdRate + ' burst 15 packets accept',
      '        ip daddr 224.0.0.17 udp dport ' + sdPort + ' log prefix "SOMEIP_SD_STORM_DROP: " drop',
      '',
      '        # 2. SOME/IP Method / Event Communication (Port ' + servicePort + ')',
      '        # Allow strictly between verified ADAS nodes',
      '        iifname "' + adasIface + '" ip saddr @adas_nodes udp dport ' + servicePort + ' accept',
      '        iifname "' + adasIface + '" ip saddr @adas_nodes tcp dport ' + servicePort + ' ct state new accept',
      '',
      '        # 3. Block Infotainment interface (' + iviIface + ') from injecting raw control RPCs',
      '        iifname "' + iviIface + '" udp dport ' + servicePort + ' log prefix "SOMEIP_IVI_INJECT_BLOCKED: " drop',
      '        iifname "' + iviIface + '" tcp dport ' + servicePort + ' log prefix "SOMEIP_IVI_INJECT_BLOCKED: " drop',
      '',
      '        # Default drop counter',
      '        counter log prefix "SOMEIP_GW_UNAUTHORIZED: " drop',
      '    }',
      '',
      '    chain forward {',
      '        type filter hook forward priority filter; policy drop;',
      '',
      '        # Strictly isolate Infotainment (' + iviIface + ') from Autonomous Drive Domain (' + adasIface + ')',
      '        iifname "' + iviIface + '" oifname "' + adasIface + '" log prefix "SOMEIP_CROSS_DOMAIN_BREACH: " drop',
      '    }',
      '}'
    ].join('\n');
  }

  /**
   * Generates Suricata Layer 7 SOME/IP & SOME/IP-SD threat signatures
   */
  function generateSuricataRules(config) {
    return [
      '# Suricata L7 SOME/IP & SOME/IP-SD Intrusion Detection Signatures',
      '# Generated by SOMEIPForge Pro - AUTOSAR SecOC / ISO 21434 Engine',
      '',
      '# 1. Alert on invalid SOME/IP Protocol Version (Must be 0x01 or 0x02)',
      'alert udp any any -> any [30490,30501] (msg:"SOMEIP-IDS: Invalid Protocol Version in 16-byte header"; flow:to_server; byte_test:1,!&,0x03,12; classtype:protocol-command-decode; sid:90014201; rev:1;)',
      '',
      '# 2. Alert on rogue SOME/IP-SD OfferService for Safety-Critical Service ID 0x1000',
      'alert udp any any -> 224.0.0.17 30490 (msg:"SOMEIP-IDS: Suspicious OfferService Broadcast for Braking Service (0x1000)"; content:"|FF FF 81 00|",offset:0,depth:4; content:"|01|",offset:24,depth:1; content:"|10 00|",offset:28,depth:2; classtype:policy-violation; priority:1; sid:90014202; rev:1;)',
      '',
      '# 3. Detect SOME/IP-SD Multicast Flood (Potential DoS / Bus Saturation)',
      'alert udp any any -> 224.0.0.17 30490 (msg:"SOMEIP-IDS: High-Frequency SOME/IP-SD Broadcast Storm Detected"; threshold:type both, track by_src, count 50, seconds 2; classtype:attempted-dos; priority:2; sid:90014203; rev:1;)',
      '',
      '# 4. Critical Alert: SOME/IP Error Response (E_E2E_WRONG_SEQUENCE or E_MALFORMED_MESSAGE)',
      'alert udp any [30490,30501] -> any any (msg:"SOMEIP-IDS: Warning - E2E Sequence or Deserialization Error Code Returned"; content:"|0C|",offset:15,depth:1; classtype:suspicious-traffic; priority:1; sid:90014204; rev:1;)',
      '',
      '# 5. Detect SOME/IP-TP (Transport Protocol) Fragment Train Flooding',
      'alert udp any any -> any 30501 (msg:"SOMEIP-IDS: Large Fragmented SOME/IP-TP Message Train"; content:"|20|",offset:14,depth:1; threshold:type both, track by_src, count 20, seconds 1; classtype:bad-unknown; priority:2; sid:90014205; rev:1;)'
    ].join('\n');
  }

  /**
   * Generates AUTOSAR Adaptive ARXML Service Interface description
   */
  function generateArxmlSnippet(opts) {
    opts = opts || {};
    var serviceName = opts.serviceName || 'VehicleBrakingService';
    var serviceId = opts.serviceId || '0x1000';
    var methodName = opts.methodName || 'RequestEmergencyBrake';
    var methodId = opts.methodId || '0x0001';

    return [
      '<?xml version="1.0" encoding="UTF-8"?>',
      '<AUTOSAR xmlns="http://autosar.org/schema/r4.0" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://autosar.org/schema/r4.0 AUTOSAR_00048.xsd">',
      '  <AR-PACKAGES>',
      '    <AR-PACKAGE>',
      '      <SHORT-NAME>Services</SHORT-NAME>',
      '      <ELEMENTS>',
      '        <SERVICE-INTERFACE>',
      '          <SHORT-NAME>' + serviceName + '</SHORT-NAME>',
      '          <NAMESPACES>',
      '            <SYMBOL-PROPS>',
      '              <SHORT-NAME>vehicle</SHORT-NAME>',
      '              <SYMBOL>vehicle</SYMBOL>',
      '            </SYMBOL-PROPS>',
      '          </NAMESPACES>',
      '          <METHODS>',
      '            <CLIENT-SERVER-OPERATION>',
      '              <SHORT-NAME>' + methodName + '</SHORT-NAME>',
      '              <FIRE-AND-FORGET>false</FIRE-AND-FORGET>',
      '            </CLIENT-SERVER-OPERATION>',
      '          </METHODS>',
      '        </SERVICE-INTERFACE>',
      '        <SOMEIP-SERVICE-INTERFACE-DEPLOYMENT>',
      '          <SHORT-NAME>' + serviceName + '_SomeipDeployment</SHORT-NAME>',
      '          <SERVICE-INTERFACE-REF DEST="SERVICE-INTERFACE">/Services/' + serviceName + '</SERVICE-INTERFACE-REF>',
      '          <SERVICE-INTERFACE-ID>' + serviceId + '</SERVICE-INTERFACE-ID>',
      '          <METHOD-DEPLOYMENTS>',
      '            <SOMEIP-METHOD-DEPLOYMENT>',
      '              <SHORT-NAME>' + methodName + '_Deployment</SHORT-NAME>',
      '              <METHOD-REF DEST="CLIENT-SERVER-OPERATION">/Services/' + serviceName + '/' + methodName + '</METHOD-REF>',
      '              <METHOD-ID>' + methodId + '</METHOD-ID>',
      '              <TRANSPORT-PROTOCOL>UDP</TRANSPORT-PROTOCOL>',
      '            </SOMEIP-METHOD-DEPLOYMENT>',
      '          </METHOD-DEPLOYMENTS>',
      '        </SOMEIP-SERVICE-INTERFACE-DEPLOYMENT>',
      '      </ELEMENTS>',
      '    </AR-PACKAGE>',
      '  </AR-PACKAGES>',
      '</AUTOSAR>'
    ].join('\n');
  }

  return {
    generateNftablesRules: generateNftablesRules,
    generateSuricataRules: generateSuricataRules,
    generateArxmlSnippet: generateArxmlSnippet
  };
}));
